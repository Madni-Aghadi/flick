enum ReportID: UInt8 {
    case mouse = 1
    case keyboard = 2
    case keyboardLEDs = 3
    case battery = 4
    case systemControl = 5
    case consumerControl = 6
    case absolutePointer = 7
}

struct MouseReport: Equatable {
    var buttons: UInt8 = 0
    var dx: Int8 = 0
    var dy: Int8 = 0
    var wheel: Int8 = 0

    var data: Data {
        Data([buttons, UInt8(bitPattern: dx), UInt8(bitPattern: dy), UInt8(bitPattern: wheel)])
    }
}

struct KeyboardReport: Equatable {
    var modifiers: UInt8 = 0
    var keys: [UInt8] = []

    var data: Data {
        var bytes = [UInt8](repeating: 0, count: 8)
        bytes[0] = modifiers
        for (i, k) in keys.prefix(6).enumerated() { bytes[2 + i] = k }
        return Data(bytes)
    }
}

enum Consumer: UInt16 {
    case none = 0
    case playPause = 0xCD, next = 0xB5, previous = 0xB6
    case mute = 0xE2, volumeUp = 0xE9, volumeDown = 0xEA
    case brightnessUp = 0x6F, brightnessDown = 0x70

    var data: Data { Data([UInt8(rawValue & 0xFF), UInt8(rawValue >> 8), 0, 0, 0]) }
}

